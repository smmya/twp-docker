#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Telegram WEB Proxy AIO: self-contained CI driver (Python 3.12+, stdlib only).

Repository needs exactly:
  .github/workflows/build.yml
  scripts/build.py
  scripts/test.py

`restore` expands the audited v2 container adapters, Go runtime, Dockerfile,
release helper, tests and deployment docs from the SHA256-verified embedded
bundle at the bottom of this file. No external wrapper repository is fetched.
Only two official upstream Git repositories are fetched at exact detected SHAs
when an update is required. Keep the embedded bundle and its checksum together.

Useful commands: restore | detect | write-plan | prepare | image | package | publish
To change the Go runtime/Dockerfile/patches, regenerate and review this bundle
rather than changing the blob blindly. Force a manual workflow run after any
wrapper-only update because normal auto builds track upstream changes only.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tarfile

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT / 'tg-aio-work' / 'project'
ARCHIVE_SHA256 = 'ca7f6df8a4870eb7bd3da444dd4d46c813eebf6c279bf834fd91e0ef2f7090c9'
EXPECTED_FILES = (
    'Dockerfile', 'runtime/main.go', 'runtime/go.mod',
    'scripts/release.py', 'scripts/smoke-test.py',
    'scripts/apply-patches.py', 'tests/test_release.py',
    'patches/tproxy-container.patch', 'patches/mtproxy-http-ip.patch',
    'upstream.json', 'public/index.html',
)


def restore() -> None:
    """Rebuild exact wrapper project files in an ephemeral directory."""
    data = base64.b64decode(''.join(ARCHIVE_BASE64.split()), validate=True)
    actual = hashlib.sha256(data).hexdigest()
    if actual != ARCHIVE_SHA256:
        raise ValueError(f'Embedded bundle SHA256 mismatch: {actual}')
    if PROJECT.exists():
        shutil.rmtree(PROJECT)
    PROJECT.mkdir(parents=True, exist_ok=False)
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as tf:
        members = tf.getmembers()
        for member in members:
            name = member.name
            if (not member.isfile() or name.startswith('/') or
                    any(part in ('', '.', '..') for part in name.split('/'))):
                raise ValueError(f'Unsafe bundle member: {name!r}')
        tf.extractall(PROJECT, members=members, filter='data')
    for relative in EXPECTED_FILES:
        if not (PROJECT / relative).is_file():
            raise ValueError(f'Missing embedded source: {relative}')
    print(f'PASS: restored {len(members)} build sources, SHA256={actual}')


def ready() -> None:
    if not all((PROJECT / p).is_file() for p in EXPECTED_FILES):
        raise RuntimeError('Run `python3 scripts/build.py restore` in this job first')


def release(command: str, passthrough: list[str]) -> None:
    ready()
    subprocess.run([sys.executable, 'scripts/release.py', command, *passthrough],
                   cwd=PROJECT, check=True)


def image() -> None:
    ready()
    plan = json.loads((PROJECT / 'build/plan.json').read_text(encoding='utf-8'))
    sha = os.environ.get('GITHUB_SHA')
    if sha and plan.get('wrapper_revision') != sha:
        raise ValueError('Current checkout differs from the detected wrapper revision')
    if plan.get('build_needed') is not True:
        raise ValueError('Refusing Docker build for unchanged upstreams')
    upstreams = plan['upstreams']
    tproxy = upstreams['tproxy-server']['commit']
    mtproxy = upstreams['MTProxy']['commit']
    version = plan['version']
    if not re.fullmatch(r'[0-9a-f]{40}', tproxy) or not re.fullmatch(r'[0-9a-f]{40}', mtproxy):
        raise ValueError('Upstream commits must be full verified SHAs')
    if not re.fullmatch(r'[0-9]{8}T[0-9]{6}Z-[0-9a-f]{8}-[0-9a-f]{8}', version):
        raise ValueError('Unexpected version label')
    if version != plan['build_date'].replace('-', '').replace(':', '') + '-' + tproxy[:8] + '-' + mtproxy[:8]:
        raise ValueError('Version does not match build date and upstream commits')
    command = ['docker', 'build', '--pull', '--platform', 'linux/amd64',
               '--build-arg', f'TPROXY_COMMIT={tproxy}',
               '--build-arg', f'MTPROXY_COMMIT={mtproxy}',
               '--build-arg', f'BUILD_VERSION={version}',
               '--build-arg', f'WRAPPER_REVISION={plan["wrapper_revision"]}',
               '--build-arg', f'BUILD_DATE={plan["build_date"]}',
               '--tag', 'twp:latest',
               '--tag', f'twp:{tproxy[:8]}-{mtproxy[:8]}', '.']
    print(f'Building one linux/amd64 image at tproxy={tproxy[:12]}, mtproxy={mtproxy[:12]}', flush=True)
    subprocess.run(command, cwd=PROJECT, check=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('restore', 'detect', 'write-plan',
                                          'prepare', 'image', 'package', 'publish'))
    args, rest = parser.parse_known_args()
    if args.command == 'restore':
        if rest:
            parser.error('restore does not accept extra arguments')
        restore()
    elif args.command == 'image':
        if rest:
            parser.error('image does not accept extra arguments')
        image()
    else:
        release(args.command, rest)
    return 0


